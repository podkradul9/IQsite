export function calculateResult(test, answers) {
  const total = Object.values(answers).reduce((sum, score) => sum + score, 0);
  const result = test.results.find((r) => total >= r.min && total <= r.max);
  return { total, result: result || test.results[test.results.length - 1] };
}

export function getReactionResult(avgMs) {
  return reactionTest.results.find((r) => avgMs <= r.max);
}

export function getReactionPercent(avgMs) {
  // Обычный диапазон реакции человека: ~180мс (отлично) — 500мс (медленно).
  // Клампим и инвертируем — быстрее время = более заполненная шкала.
  const clamped = Math.min(Math.max(avgMs, 180), 500);
  return Math.round(100 - ((clamped - 180) / (500 - 180)) * 100);
}
